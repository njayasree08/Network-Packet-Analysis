# ── 2. Aliases: simulator name → model column name ────────────────────────────
FEATURE_ALIASES: Dict[str, str] = {
    # Add mappings here if your dataset uses different column names
    # e.g., "Flow Bytes/s" → "Flow_Bytes_s" is already handled below
    "Flow Bytes/s": "Flow_Bytes_s",
    "Flow Packets/s": "Flow_Packets_s",
    "Total Length of Fwd Packets": "Total_Length_of_Fwd_Packets",
    "Total Length of Bwd Packets": "Total_Length_of_Bwd_Packets",
}


# ── 3. Default values for missing features ────────────────────────────────────
DEFAULT_VALUES: Dict[str, Any] = {col: 0 for col in MODEL_FEATURE_COLUMNS}


def map_features(raw_features: Dict[str, Any]) -> pd.DataFrame:
    """
    Convert raw simulator features into a single-row DataFrame matching
    MODEL_FEATURE_COLUMNS exactly.

    Parameters
    ----------
    raw_features : dict
        Feature dict produced by network/traffic.py generate_flow_features()

    Returns
    -------
    pd.DataFrame  — shape (1, len(MODEL_FEATURE_COLUMNS))
    """
    # Apply aliases
    aliased = {}
    for k, v in raw_features.items():
        mapped_key = FEATURE_ALIASES.get(k, k)
        aliased[mapped_key] = v

    # Build row using model columns, filling missing with defaults
    row = {}
    for col in MODEL_FEATURE_COLUMNS:
        if col in aliased:
            row[col] = aliased[col]
        else:
            row[col] = DEFAULT_VALUES.get(col, 0)

    df = pd.DataFrame([row], columns=MODEL_FEATURE_COLUMNS)

    # Replace inf/nan
    df.replace([np.inf, -np.inf], 0, inplace=True)
    df.fillna(0, inplace=True)

    return df


def get_feature_names() -> List[str]:
    return MODEL_FEATURE_COLUMNS.copy()
